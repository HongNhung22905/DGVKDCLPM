import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createApp } from '../src/server.ts';
import { RunStore } from '../src/store.ts';

test('API local: nhập XML, xem chi tiết, tải lại XML, lịch sử và lỗi đầu vào', async t => {
  const directory = await mkdtemp(path.join(tmpdir(), 'hsk-api-'));
  const { server, runner } = await createApp(new RunStore(directory));
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await runner.shutdown(); server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve())); await rm(directory, { recursive: true, force: true }); });
  const address = server.address();
  assert.ok(address && typeof address === 'object');
  const base = `http://127.0.0.1:${address.port}`;
  const get = (route: string) => fetch(base + route);
  const post = (route: string, data: unknown, headers: Record<string, string> = {}) => fetch(base + route, { method: 'POST', headers: { 'Content-Type': 'application/json', ...headers }, body: JSON.stringify(data) });
  assert.equal((await get('/')).status, 200);
  assert.equal((await get('/app.js')).status, 200);
  const config = await (await get('/api/config')).json() as any;
  assert.ok(config.groups.length > 3);
  assert.equal('apiKey' in config.gemini, false);
  const xml = '<testsuite tests="2"><testcase name="ok"/><testcase name="failed"><failure message="bad"/></testcase></testsuite>';
  const imported = await post('/api/import', { filename: 'past.xml', xml });
  assert.equal(imported.status, 201);
  const run = await imported.json() as any;
  assert.equal(run.status, 'failed');
  assert.equal(run.source, 'import');
  assert.equal(await (await get(`/api/runs/${run.id}/xml`)).text(), xml);
  assert.equal((await (await get(`/api/runs/${run.id}`)).json() as any).report.summary.total, 2);
  assert.equal((await (await get('/api/runs')).json() as any[]).length, 1);
  assert.equal((await post('/api/import', { filename: 'bad.xml', xml: '<html/>' })).status, 400);
  assert.equal((await post('/api/runs', { groupId: '../../arbitrary' })).status, 400);
  assert.equal((await post('/api/import', { filename: 'a.xml', xml }, { Origin: 'https://outside.example' })).status, 403);
  assert.equal((await get('/.env')).status, 404);
  assert.equal((await get('/src/server.ts')).status, 404);
  delete process.env.GEMINI_API_KEY;
  const analysis = await post(`/api/runs/${run.id}/analysis`, {});
  assert.equal(analysis.status, 400);
  assert.match((await analysis.json() as any).error, /Chưa cấu hình/);
});
